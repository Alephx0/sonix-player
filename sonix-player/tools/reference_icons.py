#!/usr/bin/env python3
"""Generate the small native reference-UI icons with the existing SVG renderer."""
from pathlib import Path
from svg_to_lvgl import render, c_array

root = Path(__file__).resolve().parents[1]
names = ['home', 'library', 'grid', 'pin', 'heart']
header = ['/* Generated by tools/reference_icons.py. */', '#pragma once', '#include "lvgl/lvgl.h"']
source = ['/* Generated by tools/reference_icons.py. */', '#include "reference_icons.h"']
for name in names:
    symbol = 'sonix_icon_' + name
    data, w, h = render(str(root / 'assets/icons' / ('sonix-' + name + '.svg')), 30)
    source.append(f'static const uint8_t {symbol}_data[] = {{\n{c_array(data)}\n}};')
    source.append(f'const lv_image_dsc_t {symbol} = {{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_ARGB8888,.w={w},.h={h},.stride={w*4}}},.data_size=sizeof({symbol}_data),.data={symbol}_data}};')
    header.append(f'extern const lv_image_dsc_t {symbol};')
(root / 'src/gui/shell/reference_icons.h').write_text('\n'.join(header) + '\n')
(root / 'src/gui/shell/reference_icons.c').write_text('\n'.join(source) + '\n')
